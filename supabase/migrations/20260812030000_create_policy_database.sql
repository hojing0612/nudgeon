-- NudgeOn policy/resource database
-- Public resource data is readable by everyone. All writes happen through the server.
-- Personal profile, saved resources, and notifications require Supabase Auth.

CREATE TYPE public.resource_kind AS ENUM ('policy', 'institution', 'program', 'seminar', 'housing_notice');
CREATE TYPE public.resource_status AS ENUM ('draft', 'review', 'published', 'archived');
CREATE TYPE public.application_status AS ENUM ('unknown', 'upcoming', 'open', 'always', 'closed');
CREATE TYPE public.eligibility_result AS ENUM ('likely', 'needs_review', 'unlikely', 'missing_information');
CREATE TYPE public.saved_resource_stage AS ENUM ('interested', 'checking_eligibility', 'preparing_documents', 'applied', 'completed', 'dismissed');
CREATE TYPE public.notification_channel AS ENUM ('email', 'push', 'sms');

CREATE TABLE public.resource_categories (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug text NOT NULL UNIQUE,
  name text NOT NULL,
  description text,
  sort_order int NOT NULL DEFAULT 0,
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

