CREATE POLICY "public_read_categories" ON public.resource_categories FOR SELECT USING (active);
CREATE POLICY "public_read_published_resources" ON public.resources FOR SELECT USING (status = 'published');
CREATE POLICY "public_read_published_category_links" ON public.resource_category_links FOR SELECT
USING (EXISTS (SELECT 1 FROM public.resources r WHERE r.id = resource_id AND r.status = 'published'));
CREATE POLICY "public_read_published_rules" ON public.eligibility_rules FOR SELECT
USING (EXISTS (SELECT 1 FROM public.resources r WHERE r.id = resource_id AND r.status = 'published'));
CREATE POLICY "public_read_published_steps" ON public.application_steps FOR SELECT
USING (EXISTS (SELECT 1 FROM public.resources r WHERE r.id = resource_id AND r.status = 'published'));
CREATE POLICY "public_read_published_sources" ON public.resource_sources FOR SELECT
USING (EXISTS (SELECT 1 FROM public.resources r WHERE r.id = resource_id AND r.status = 'published'));

CREATE POLICY "users_read_own_profile" ON public.user_connection_profiles FOR SELECT USING (auth.uid() = user_id);
CREATE POLICY "users_insert_own_profile" ON public.user_connection_profiles FOR INSERT WITH CHECK (auth.uid() = user_id);
CREATE POLICY "users_update_own_profile" ON public.user_connection_profiles FOR UPDATE USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);
CREATE POLICY "users_delete_own_profile" ON public.user_connection_profiles FOR DELETE USING (auth.uid() = user_id);

CREATE POLICY "users_manage_own_saved_resources" ON public.user_saved_resources FOR ALL
USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);
CREATE POLICY "users_manage_own_notifications" ON public.notification_rules FOR ALL
USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);

GRANT SELECT ON public.resource_categories, public.resources, public.resource_category_links,
  public.eligibility_rules, public.application_steps, public.resource_sources TO anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.user_connection_profiles,
  public.user_saved_resources, public.notification_rules TO authenticated;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO authenticated;

